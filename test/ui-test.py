# python3 -I test/ui-test.py <port> [screenshot-dir] - drives the settings page (served by test/ui-serve.js) in headless
# Chrome, the way a person would. Fails on any JavaScript error or a step that doesn't work.
import json, sys, time, os, tempfile
from playwright.sync_api import sync_playwright

port = sys.argv[1] if len(sys.argv) > 1 else '8599'
shots = sys.argv[2] if len(sys.argv) > 2 else None
base = f'http://127.0.0.1:{port}'
files = os.path.join(tempfile.gettempdir(), f'he-ui-files-{port}')  # written by ui-serve.js
errors, checks = [], []
def check(name, cond):
    checks.append(name)
    if not cond: raise AssertionError(name)
    print('ok', name)

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True)
    pg = b.new_page(viewport={'width': 1100, 'height': 900}, accept_downloads=True)
    pg.on('pageerror', lambda e: errors.append(str(e) + ' ' + str(e.stack)[:400]))
    pg.on('console', lambda m: m.type == 'error' and errors.append(m.text))
    dialogs = []
    def on_dialog(d): dialogs.append(d.message); d.dismiss()
    pg.on('dialog', on_dialog)
    pg.goto(base)
    pg.wait_for_selector('#ui')
    page = pg
    pg = next(f for f in page.frames if f.url.endswith('/inner'))  # everything below runs inside the sandboxed frame
    def answer(text=None):
        pg.wait_for_selector('.ask [data-askok]', timeout=5000)
        if text is not None: pg.fill('.ask [data-askin]', text)
        pg.click('.ask [data-askok]')
    def screenshot(name):
        if shots: page.screenshot(path=f'{shots}/{name}', full_page=True)
    pg.wait_for_function("document.querySelector('#status .big') && /W/.test(document.querySelector('#status .big').textContent)", timeout=15000)
    check('live watts shown', True)
    for d in pg.query_selector_all('details.sec'): d.evaluate('d => d.open = true')
    toasts = lambda: pg.evaluate('window.__toasts')
    # meter: channel list from the meter itself
    pg.wait_for_function("document.querySelectorAll('#emChannel option').length >= 4")
    check('meter channels listed', 'CT clamp 1' in pg.inner_text('#emChannel'))
    pg.fill('#threshold', '50'); pg.click('#saveMeter'); time.sleep(.5)
    check('meter saved', any(t[1] == 'Saved' for t in toasts()))
    # Shellys: a bad address refused, good ones read
    pg.fill('#shellyAdd', '8.8.8.8'); pg.click('#addShelly'); time.sleep(.5)
    check('internet address refused', any(t[0] == 'error' and 'home network' in t[1] for t in toasts()))
    pg.fill('#shellyAdd', f'127.0.0.1:{int(port) + 2} 127.0.0.1:{int(port) + 3}'); pg.click('#addShelly')
    pg.wait_for_function("document.querySelector('#dev').textContent.includes('Gen2+') && document.querySelector('#dev').textContent.includes('HomeKit firmware')", timeout=15000)
    check('both Shelly kinds recognised', True)
    pg.wait_for_function("document.querySelector('#dev').textContent.includes('Dryer')", timeout=10000)
    # readings not tracked yet appear under Appliances → Found; one can be hidden and shown again
    pg.wait_for_function("document.querySelector('#pat').textContent.includes('Found, not set up yet')", timeout=10000)
    check('untracked readings in Found', 'Dryer' in pg.inner_text('#pat') and 'device reading' in pg.inner_text('#pat'))
    check('no separate Devices heading', pg.query_selector('#sec-dev') is None)
    dryer_id = pg.get_attribute('#pat button[data-hide][data-hide^="shrpc:"]', 'data-hide')
    pg.click(f'#pat button[data-hide="{dryer_id}"]'); time.sleep(.8)
    check('a reading can be hidden from Found', '1 hidden' in pg.inner_text('#pat') and pg.query_selector(f'#pat button[data-hide="{dryer_id}"]') is None)
    pg.click('#pat button[data-showhidden]'); time.sleep(.3); pg.click(f'#pat button[data-unhide="{dryer_id}"]'); time.sleep(.8)
    check('and shown again', pg.query_selector(f'#pat button[data-hide="{dryer_id}"]') is not None)
    # Matter: a wrong code, then a GRILLPLATS-shaped plug
    pg.fill('#mName', 'Grill plug'); pg.fill('#mCode', 'not a code'); pg.click('#addMatter'); time.sleep(.5)
    check('bad pairing code refused', any(t[0] == 'error' and 'pairing code' in t[1] for t in toasts()))
    pg.fill('#mCode', '1234-567-8901'); pg.click('#addMatter')
    pg.wait_for_function("document.querySelector('#dev').textContent.includes('Connected')", timeout=15000)
    check('Matter device connected', 'GRILLPLATS' in pg.inner_text('#dev'))
    screenshot('1-devices.png')
    # restore a backup, chosen as a file
    check('no backups on the computer yet', 'No backups on the Homebridge computer yet' in pg.inner_text('#data'))
    pg.set_input_files('#impFile', os.path.join(files, 'saved.json'))
    pg.wait_for_selector('.ask [data-askok]', timeout=5000)
    check('import asks on the page, not with a pop-up', pg.is_visible('.ask') and not dialogs)
    answer()
    pg.wait_for_function("document.querySelectorAll('#appl button[data-edit]').length >= 4", timeout=15000)
    check('imported appliances listed', 'Kettle' in pg.inner_text('#appl') and 'Last import' in pg.inner_text('#data'))
    # edit an appliance
    pg.click('#appl button[data-edit]'); pg.wait_for_selector('#appl [data-form]')
    fid = pg.get_attribute('#appl [data-form]', 'data-form')
    pg.select_option(f'[data-roompick="ed-{fid}"] [data-roomsel]', '__new')
    check('"+ New room…" opens a box for its name', pg.is_visible(f'[data-roompick="ed-{fid}"] [data-roomnew]'))
    pg.fill(f'[data-roompick="ed-{fid}"] [data-roomnew]', 'Laundry'); pg.select_option(f'[data-form="{fid}"] [data-f="status"]', 'switch')
    time.sleep(3.5)  # a refresh must not wipe the open form
    check('edit form survives a refresh', pg.input_value(f'[data-roompick="ed-{fid}"] [data-roomnew]') == 'Laundry')
    pg.select_option(f'#ic-{fid}', 'none')
    pg.click(f'button[data-save="{fid}"]'); time.sleep(.8)
    check('appliance edited, new room created', 'Laundry' in pg.inner_text('#appl'))
    check('"No icon" shows nothing', pg.evaluate(f"document.querySelector('button[data-edit=\"{fid}\"]').closest('tr').querySelector('.ico').textContent") == '')
    pg.click(f'button[data-edit="{fid}"]'); pg.wait_for_selector(f'#ic-{fid}')
    check('"No icon" stays chosen', pg.input_value(f'#ic-{fid}') == 'none')
    opts = pg.eval_on_selector(f'[data-form="{fid}"] [data-f="status"]', 'e => [...e.options].map(o => o.textContent)')
    check('running tile: the new types offered', all(t in opts for t in ['Outlet', 'Light', 'Fan', 'Air purifier', 'Humidifier', 'Dehumidifier', 'Heater', 'Air conditioner']))
    pg.select_option(f'[data-form="{fid}"] [data-f="status"]', 'dehumidifier')
    pg.select_option(f'#ic-{fid}', 'kettle'); pg.click(f'button[data-save="{fid}"]'); time.sleep(.8)
    pg.click(f'button[data-edit="{fid}"]'); pg.wait_for_selector(f'#ic-{fid}')
    check('running tile: Dehumidifier saved', pg.input_value(f'[data-form="{fid}"] [data-f="status"]') == 'dehumidifier')
    pg.click(f'button[data-edit="{fid}"]'); time.sleep(.3)
    check('an icon can be chosen again', pg.evaluate(f"document.querySelector('button[data-edit=\"{fid}\"]').closest('tr').querySelector('.ico').textContent") == '🫖')
    # an appliance measured through another Homebridge plugin before: linked to a device from its Edit panel, history kept
    lamp = pg.evaluate("[...document.querySelectorAll('#appl tr')].find(r => r.textContent.includes('Hallway lamp')).querySelector('[data-edit]').dataset.edit")
    pg.click(f'button[data-edit="{lamp}"]'); pg.wait_for_selector(f'[data-link="{lamp}"]')
    check('"measured before" explained with Keep it on steps', pg.is_visible(f'button[data-keep="{lamp}"]'))
    dryer = pg.evaluate(f"[...document.querySelectorAll('[data-link=\"{lamp}\"] option')].find(o => o.textContent.startsWith('Dryer')).value")
    pg.select_option(f'[data-link="{lamp}"]', dryer); pg.click(f'button[data-dolink="{lamp}"]'); time.sleep(1)
    check('appliance linked to its device, no duplicate', 'measured before' not in pg.inner_text('#appl') and pg.inner_text('#appl').count('Hallway lamp') == 1 and '→ Hallway lamp' in pg.inner_text('#dev'))
    check('the appliance shows what measures it', 'via Dryer' in pg.inner_text('#appl'))
    pg.click(f'button[data-edit="{lamp}"]'); pg.wait_for_selector(f'[data-form="{lamp}"]')
    check('a measured appliance explains its cycles', 'Cycles learned' in pg.inner_text(f'[data-form="{lamp}"]') and 'time left' in pg.inner_text(f'[data-form="{lamp}"]'))
    pg.click(f'button[data-edit="{lamp}"]'); time.sleep(.3)
    check('a tracked reading leaves Found', not pg.query_selector(f'#pat button[data-hide="{dryer_id}"]'))
    check('to-do no longer lists it', 'measured through Homebridge' not in pg.inner_text('#todo'))
    groups = pg.evaluate("[...document.querySelectorAll('#appl tr.grp')].map(r => r.textContent.trim())")
    check('appliances grouped by room, "No room" last', any(g.startswith('Laundry') for g in groups) and any(g.startswith('Kitchen') for g in groups) and groups[-1].startswith('No room'))
    # unnamed steps: wait for the repeating 1.2 kW load, then name it
    row = "[...document.querySelectorAll('#pat tr')].find(r => /^1\\.[12]\\d kW/.test(r.cells[0]?.textContent || ''))"
    try: pg.wait_for_function(f"!!{row}", timeout=150000)
    except Exception: print('unnamed steps were:', pg.inner_text('#pat')); raise
    pg.evaluate(f"{row}.querySelector('button[data-name]').click()"); pg.wait_for_selector('#nmName')
    check('the new room is offered next time', 'Laundry' in pg.inner_text('[data-roompick="nm"] [data-roomsel]'))
    pg.fill('#nmName', 'Toaster'); pg.select_option('[data-roompick="nm"] [data-roomsel]', 'Kitchen'); pg.click('#pat button[data-doname]'); time.sleep(.8)
    check('steps named', 'Toaster' in pg.inner_text('#appl'))
    check('imported Matter devices connect', 'Connecting' not in pg.inner_text('#dev'))
    # electricity plan: time of use with a period
    pg.select_option('#pMode', 'tou'); pg.fill('#pRate', '0.3'); pg.fill('#pFixed', '2.1')
    pg.fill('#plan tr[data-per] [data-p="rate"]', '0.15'); pg.check('#pCheap'); pg.click('#savePlan'); time.sleep(.8)
    check('plan saved', any(t[1] == 'Plan saved' for t in toasts()) and pg.input_value('#pMode') == 'tou')
    check('cheap tile on with the plan', pg.is_checked('#pCheap'))
    # summary with costs
    pg.click('#summary button[data-days="7"]'); time.sleep(1)
    check('summary with cost', 'Whole house' in pg.inner_text('#summary') and 'Cost' in pg.inner_text('#summary'))
    pg.fill('#tOtherName', 'Everything else'); pg.click('#saveTiles'); time.sleep(.5)
    check('Other outlet renamed', pg.input_value('#tOtherName') == 'Everything else')
    screenshot('2-appliances.png')
    # a backup, in a frame that can't download (like the Homebridge UI): kept on the Homebridge computer and listed
    n_toasts = len(toasts()); pg.click('#export')
    pg.wait_for_function("window.__toasts.some(t => /Saved on the Homebridge computer/.test(t[1]))", timeout=15000)
    pg.wait_for_selector('#data button[data-impbk]', timeout=5000)
    check('backup saved on the Homebridge computer and listed', len(pg.query_selector_all('#data button[data-impbk]')) == 1 and not any(t[0] == 'error' for t in toasts()[n_toasts:]))
    # and imported from that list again: nothing lost or doubled
    n_before = len(pg.query_selector_all('#appl button[data-edit]'))
    pg.click('#data button[data-impbk]'); answer()
    pg.wait_for_function("document.querySelector('#data').textContent.includes('the backup of')", timeout=15000)
    time.sleep(1)
    check('its own backup imported again, nothing lost or doubled', len(pg.query_selector_all('#appl button[data-edit]')) == n_before)
    # Ways to save, after importing a month of history: savings per week, month and year; hiding and showing again
    pg.evaluate("document.querySelector('#sec-set').open = true; document.querySelector('#sec-today').open = true")
    pg.set_input_files('#impFile', os.path.join(files, 'month.json')); answer()
    pg.wait_for_function("document.querySelector('#tips').textContent.includes('cheaper hours')", timeout=20000)
    tips = pg.inner_text('#tips')
    check('a tip from the measured dryer, per week, month and year', 'Run the Dryer in cheaper hours' in tips and 'a week' in tips and 'a month' in tips and 'a year' in tips)
    pg.click('#tips .tip button[data-tipno^="shift:"]'); time.sleep(1)
    check('a tip can be hidden', 'cheaper hours' not in pg.inner_text('#tips') and 'hidden' in pg.inner_text('#tips'))
    pg.click('#tips button[data-tipsall]'); time.sleep(1)
    check('hidden tips shown again', 'cheaper hours' in pg.inner_text('#tips'))
    screenshot('4-tips.png')
    # cancelling a question does nothing
    pg.click('#data button[data-impbk]'); pg.click('.ask [data-askno]'); time.sleep(.3)
    check('cancel leaves things as they were', not pg.is_visible('.ask'))
    # filters on the two lists
    pg.evaluate("document.querySelector('#sec-appl').open = true; document.querySelector('#sec-set').open = true")
    check('appliance filters shown for a longer list', pg.is_visible('#aq'))
    pg.fill('#aq', 'kett'); time.sleep(.3)
    check('search: only matching appliances, "1 of N"', 'Kettle' in pg.inner_text('#appl') and 'Toaster' not in pg.inner_text('#appl') and pg.inner_text('#acount').startswith('1 of'))
    pg.fill('#aq', 'zzzz'); time.sleep(.3)
    check('no match offers "Show all"', 'No appliance matches' in pg.inner_text('#appl'))
    pg.click('#appl [data-clearf]'); time.sleep(.3)
    check('"Show all" clears the filters', pg.input_value('#aq') == '' and 'Toaster' in pg.inner_text('#appl'))
    pg.select_option('#ashow', 'measured'); time.sleep(.3)
    check('show: measured by a device', 'Grill' in pg.inner_text('#appl') and 'Toaster' not in pg.inner_text('#appl'))
    pg.select_option('#ashow', ''); pg.select_option('#aroom', 'Kitchen'); time.sleep(.3)
    check('room filter', 'Kettle' in pg.inner_text('#appl') and 'Garage heater' not in pg.inner_text('#appl'))
    pg.select_option('#aroom', '')
    pg.select_option('#dshow', 'matter'); time.sleep(.3)
    check('devices: Matter only', 'Grill plug' in pg.inner_text('#dev') and 'Gen2+' not in pg.inner_text('#dev'))
    pg.select_option('#dshow', 'shelly'); time.sleep(.3)
    check('devices: Shellys only', 'Gen2+' in pg.inner_text('#dev') and 'Grill plug' not in pg.inner_text('#dev'))
    pg.select_option('#dshow', ''); pg.fill('#dq', '8601'); time.sleep(.3)
    check('devices: search by address', 'SNPL' in pg.inner_text('#dev') and 'Grill plug' not in pg.inner_text('#dev'))
    pg.fill('#dq', '')
    # removing a Shelly by its ✕
    pg.click(f'button[data-shrm="127.0.0.1:{int(port) + 3}"]'); answer(); time.sleep(1)
    check('Shelly removed', 'HomeKit firmware' not in pg.inner_text('#dev'))
    # the open headings are remembered
    pg.evaluate("document.querySelector('#sec-set').open = false")
    page.reload(); page.wait_for_selector('#ui'); time.sleep(1.5)
    pg = next(f for f in page.frames if f.url.endswith('/inner'))
    check('open headings remembered', pg.evaluate("document.querySelector('#sec-appl').open && !document.querySelector('#sec-set').open"))
    pg.fill('#aq', 'toast'); time.sleep(.3)
    page.reload(); page.wait_for_selector('#ui'); time.sleep(1.5)
    pg = next(f for f in page.frames if f.url.endswith('/inner'))
    pg.wait_for_selector('#appl button[data-edit]', timeout=10000)
    check('filters remembered after a reload', pg.input_value('#aq') == 'toast' and 'Kettle' not in pg.inner_text('#appl'))
    pg.fill('#aq', '')
    # Find Shellys: the ones added already are marked; a new one is added from the list; a locked one can't be
    pg.evaluate("document.querySelector('#sec-set').open = true"); pg.click('#findShellys')
    pg.wait_for_function("document.querySelector('#found').textContent.includes('Found 5 Shellys')", timeout=30000)
    found = pg.inner_text('#found')
    # (the HomeKit-firmware one was removed above, so it shows as not added)
    check('Find Shellys: all kinds found, added ones marked, a password reported', 'Workshop' in found and 'password set' in found and found.count('Added') == 1 and '3 not added yet' in found and 'Gen1' in found and 'HomeKit firmware' in found and 'PlusPlugS' in found)
    pg.click(f'#found button[data-addfound="127.0.0.1:{int(port) + 6}"]')
    pg.wait_for_function(f"document.querySelector('#dev').textContent.includes('127.0.0.1:{int(port) + 6}')", timeout=15000)
    time.sleep(.5)
    check('Find Shellys: added from the list, read like any other', pg.inner_text('#found').count('Added') == 2 and '2 not added yet' in pg.inner_text('#found'))
    # a device named with HTML: listed and added as plain text, nothing runs
    pg.click(f'#found button[data-addfound="127.0.0.1:{int(port) + 8}"]')
    pg.wait_for_function("document.querySelector('#dev').textContent.includes('onerror')", timeout=15000); time.sleep(1)
    check('a device name with HTML in it shows as text and never runs', pg.evaluate('window.__pwned') is None and not pg.query_selector('#dev img, #found img, #pat img') and '<img' in pg.inner_text('#dev'))
    pg.click('#closeFound'); time.sleep(.3)
    check('Find Shellys: closed', pg.inner_text('#found').strip() == '')
    screenshot('6-find.png')
    # the web page: a PIN set here, then the page on its own port in a separate window
    pg.evaluate("document.querySelector('#sec-set').open = true")
    check('web page card shows its address', f':{int(port) + 5}/' in pg.inner_text('#webcard'))
    pg.fill('#webPin', '4826'); pg.click('#saveWebPin'); time.sleep(.8)
    check('PIN set', 'Change PIN' in pg.inner_text('#webcard'))
    # (the page's security policy blocks the test tool's own page scripts; test/web.test.js checks that policy itself)
    w = b.new_context(bypass_csp=True, accept_downloads=True, viewport={'width': 1100, 'height': 900}).new_page()
    w.on('pageerror', lambda e: errors.append('web: ' + str(e)))
    w.on('dialog', on_dialog)
    w.goto(f'http://127.0.0.1:{int(port) + 5}/')
    w.wait_for_selector('#he-pin', state='visible', timeout=10000)
    w.fill('#he-pin', '0000x'); w.click('#he-go'); time.sleep(.5)
    check('web page: a wrong PIN is refused', "isn't right" in w.inner_text('#he-login-err'))
    w.fill('#he-pin', '4826'); w.click('#he-go')
    w.wait_for_function("document.querySelector('#status .big') && /W/.test(document.querySelector('#status .big').textContent)", timeout=15000)
    w.evaluate("for (const d of document.querySelectorAll('details.sec')) d.open = true"); time.sleep(3.5)
    check('web page: Today, Appliances, Devices and Settings work', 'Kettle' in w.inner_text('#appl') and 'Gen2+' in w.inner_text('#dev') and 'Ways to save' in w.inner_text('#tips'))
    check('web page: no PIN controls on it', not w.query_selector('#saveWebPin'))
    with w.expect_download() as dl: w.click('#export')
    data = json.loads(open(dl.value.path()).read())
    check('web page: the backup downloads too, without the PIN', len(data['sigs']) >= 5 and 'savedAs' not in data and not (data['settings'].get('web') or {}).get('pin'))
    if shots: w.screenshot(path=f'{shots}/5-web.png', full_page=True)
    w.click('#he-signout'); w.wait_for_selector('#he-pin', state='visible', timeout=10000)
    check('web page: signed out', w.is_visible('#he-pin'))
    w.close()
    # phone width: nothing wider than the screen
    page.set_viewport_size({'width': 390, 'height': 800}); time.sleep(.5)
    check('fits a phone', pg.evaluate('document.documentElement.scrollWidth') <= 392)
    screenshot('3-phone.png')
    log = json.loads(pg.evaluate("fetch('/log').then(r => r.text())"))
    bad = [m for l, m in log if l == 'error']
    check('no errors in the plugin log', not bad)
    check('no browser pop-ups were used', not dialogs)
    b.close()
if errors: print('JS errors:', errors); sys.exit(1)
print(f'{len(checks)} checks passed')
